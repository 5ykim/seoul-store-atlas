import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';

const { chromium } = await import(process.argv[2] ? pathToFileURL(process.argv[2]).href : 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true, timeout: 30000 });
const base = process.argv[3] || 'http://127.0.0.1:4174/';
const root = resolve(import.meta.dirname, '..');
await mkdir(resolve(root, '.qa'), { recursive: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 2160 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('response', (response) => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
try {
  await page.goto(base);
  await page.waitForFunction(() => window.__atlasReady === true, { timeout: 20000 });
  assert.equal(await page.locator('#map path').count(), 425);
  assert.equal(await page.locator('#scatter circle').count(), 425);
  assert.equal(await page.locator('#dong option').count(), 425);
  assert.equal(await page.locator('#change-map path').count(), 425);
  assert.equal(await page.locator('#quarter').inputValue(), 'annual');
  assert.match(await page.locator('#reference-note').innerText(), /636,753.75/);
  assert.equal(await page.locator('.trend-card').count(), 3);
  const explanation = page.locator('#falling-list details').first();
  await explanation.locator('summary').click();
  assert.match(await explanation.innerText(), /일반의류/);
  assert.match(await explanation.innerText(), /829/);
  assert.match(await explanation.innerText(), /40.8%/);
  assert.ok(await explanation.locator('table').count() >= 1);
  await explanation.locator('summary').click();
  const titleSize = await page.locator('h1').evaluate((e) => parseFloat(getComputedStyle(e).fontSize));
  const subtitleSize = await page.locator('.hero-subtitle').evaluate((e) => parseFloat(getComputedStyle(e).fontSize));
  assert.ok(titleSize > subtitleSize);
  assert.match(await page.locator('#selected-name').innerText(), /신당동/);
  await page.screenshot({ path: resolve(root, 'store-atlas-preview.png') });
  await page.screenshot({ path: resolve(root, '.qa/desktop-full.png'), fullPage: true });
  await page.locator('.change-section').screenshot({ path: resolve(root, '.qa/quarter-changes.png') });
  await page.selectOption('#quarter', '20251');
  assert.match(await page.locator('#reference-note').innerText(), /1분기/);
  await page.locator('[data-mode="entropy"]').click();
  const fixedLegend = await page.locator('#legend').innerText();
  await page.selectOption('#quarter', '20254');
  assert.equal(await page.locator('#legend').innerText(), fixedLegend);
  await page.locator('#quarter-slider').fill('1');
  assert.equal(await page.locator('#quarter').inputValue(), '20252');
  await page.locator('#play').click();
  await page.waitForFunction(() => document.querySelector('#quarter').value === '20253', {timeout:8000});
  await page.locator('#play').click();
  assert.equal(await page.locator('#play').getAttribute('aria-pressed'), 'false');
  await page.locator('#rising-list button').first().click();
  assert.match(await page.locator('#trend-title').innerText(), /고덕2동/);
  const changeFirst = page.locator('#change-map path').first();
  await changeFirst.click({force:true});
  assert.ok(await page.locator('#trend-reading').innerText());
  await page.selectOption('#district', '강남구');
  assert.ok(await page.locator('#dong option').count() < 425);
  const before = await page.locator('#selected-name').innerText();
  await page.locator('[data-mode="entropy"]').click();
  assert.match(await page.locator('#legend').innerText(), /5분위/);
  const first = page.locator('#map path:not(.faded)').first();
  await first.click({ force: true });
  assert.match(await page.locator('#selected-name').innerText(), /강남구/);
  await page.locator('#reset').click();
  assert.equal(await page.locator('#scatter circle').count(), 425);
  await page.locator('#scatter circle').nth(10).click({ force: true });
  assert.ok(await page.locator('#selected-total').innerText());
  await page.locator('[data-type="3"]').click();
  assert.match(await page.locator('#ranking-note').innerText(), /밀도 낮음 · 다양성 낮음/);
  const csv = await page.request.get(new URL('data/dong-metrics.csv', base).href);
  assert.equal(csv.status(), 200);
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
  mobile.on('pageerror', (e) => errors.push(e.message));
  await mobile.goto(base);
  await mobile.waitForFunction(() => window.__atlasReady === true);
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await mobile.screenshot({ path: resolve(root, '.qa/mobile-full.png'), fullPage: true });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: 'PASS', boundaryCount: 425, annualDefault:true, smallerSubtitle:true, fixedColorBreaks:true, playback:true, slider:true, changeMap:true, threeTrendCharts:true, quarterSwitch: true, districtFilter: true, mapClick: true, scatterClick: true, csvDownload: true, mobileNoOverflow: true, consoleErrors: errors, firstGangnamSelection: before }));
} finally { await browser.close(); }
